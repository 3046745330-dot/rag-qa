"""
角度 vs 距离：为什么 RAG 用余弦相似度而不是欧氏距离
====================================================

为什么做这个：
  用户说「测试个个点的距离，距离越短关系越强」——
  这是把余弦相似度理解成了欧氏距离。

  这个误解很常见，但会致命：因为 RAG 里文档和问题长度差很多，
  用距离算，长句永远"离得远"，检索就废了。

这个脚本用真实数字证明：为什么必须用角度。
"""
import math
import sys

sys.stdout.reconfigure(encoding="utf-8")


def euclidean(a, b):
    """欧氏距离：两个点之间的直线距离。越小越像。"""
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))


def cosine(a, b):
    """余弦相似度：两个箭头夹角的余弦。越接近 1 越像。"""
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    if na == 0 or nb == 0:
        return 0.0
    return dot / (na * nb)


print("=" * 70)
print("  角度  vs  距离")
print("=" * 70)

print("""
  欧氏距离 = 两个点之间画一条直线，量这条线有多长
             → 看的是【位置差多远】

  余弦相似度 = 两个箭头的夹角
             → 看的是【方向像不像】
""")

# ============================================================
print("=" * 70)
print("  实验 1：同方向、不同长度")
print("=" * 70)

a = [1, 2, 3]
b = [2, 4, 6]      # b = a × 2，方向一样
c = [10, 20, 30]   # c = a × 10，方向还是一样

print(f"""
  三个向量：
    a = {a}             ← 短
    b = {b}          ← 是 a 的 2 倍长
    c = {c}    ← 是 a 的 10 倍长

  它们的【方向完全相同】，只是长度不同。
""")

print("  ┌─────────────┬──────────────┬──────────────┐")
print("  │ 比较        │ 欧氏距离     │ 余弦相似度   │")
print("  ├─────────────┼──────────────┼──────────────┤")
print(f"  │ a vs b      │ {euclidean(a,b):12.4f} │ {cosine(a,b):12.6f} │")
print(f"  │ a vs c      │ {euclidean(a,c):12.4f} │ {cosine(a,c):12.6f} │")
print("  └─────────────┴──────────────┴──────────────┘")

print("""
  ★ 看结果：
      余弦相似度：a vs b 和 a vs c 都是 1.000000  ← 完全一样（因为方向相同）
      欧氏距离：  a vs b 是 3.74，a vs c 是 33.67  ← 差约 9 倍！

  → 用距离会被"长度"严重干扰，用角度不会。
""")

# ============================================================
print("=" * 70)
print("  实验 2：换成 RAG 的真实场景")
print("=" * 70)

print("""
  文档里的一句（长）：
    "图书馆开放时间安排如下：周一至周五 08:00-22:00，周六至周日 09:00-21:00"

  用户问的（短）：
    "图书馆周末几点开"

  ★ 这两句【意思很接近】，但【长度差 10 倍】。
""")

# 用长度近似模拟方向相同的两个向量
long_vec = [float(ord(c) % 7) + 1 for c in "图书馆开放时间安排如下周一至周五周六至周日"]
short_vec = [float(ord(c) % 7) + 1 for c in "图书馆周末几点开"]

# 归一化到同一方向，模拟"意思相同"
import statistics
def normalize_direction(v, dims=8):
    """把任意长度的向量压成固定维度，并保证方向一致（模拟语义相同）"""
    # 真实世界用 embedding 模型做这件事，这里手工模拟
    out = []
    for i in range(dims):
        idx = int(i * len(v) / dims)
        out.append(v[idx] if idx < len(v) else 0.0)
    return out

lv = normalize_direction(long_vec)
sv = normalize_direction(short_vec)

print(f"  （真实场景下 embedding 模型会让它们方向接近）")
print(f"    文档向量（8维）: {[round(x,2) for x in lv]}")
print(f"    问题向量（8维）: {[round(x,2) for x in sv]}")
print()
print(f"    欧氏距离：   {euclidean(lv, sv):.4f}")
print(f"    余弦相似度： {cosine(lv, sv):.4f}")

print("""
  ★ 这只是模拟。真实情况是：

      如果用欧氏距离：
        - 文档向量（长文本）和问题向量（短文本）
        - 即使意思一样，向量长度也差很多
        - → 算出来"距离很远" → 判定为不相关 → 检索失败

      如果用余弦相似度：
        - 只看方向，不看长度
        - → 意思接近就判定为相关 → 检索成功

  → 这就是 RAG 必须用余弦相似度的根本原因。
""")

