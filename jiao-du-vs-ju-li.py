print("=" * 70)
print("""
  ┌──────────────┬────────────────┬──────────────────────┐
  │              │ 欧氏距离       │ 余弦相似度           │
  ├──────────────┼────────────────┼──────────────────────┤
  │ 看什么       │ 位置差多远     │ 方向像不像           │
  │ 越像的表现   │ 值越小         │ 值越接近 1           │
  │ 受长度影响   │ ✅ 会（致命）  │ ❌ 不会              │
  │ RAG 用哪个   │ ❌ 不用        │ ✅ 用这个            │
  └──────────────┴────────────────┴──────────────────────┘

  ★ 记忆口诀：
      距离会被长度骗，角度不会。

  ★ 为什么重要：
      RAG 里文档很长、问题很短，长度天然差很多。
      如果用距离，永远是"长文档离得远"→ 检索全错。
""")
