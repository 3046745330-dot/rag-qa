def main():
    written, skipped = [], []
    for doc_id, title, body in NEW_DOCS:
        path = os.path.join(DOCS_DIR, f"{doc_id}.md")
        if os.path.exists(path):
            skipped.append(doc_id)
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# {title}\n\n{body.strip()}\n")
        written.append({"id": doc_id, "title": title, "chars": len(body.strip())})

    # 重建索引
    all_docs = []
    for name in sorted(os.listdir(DOCS_DIR)):
        if not name.endswith(".md"):
            continue
        with open(os.path.join(DOCS_DIR, name), encoding="utf-8") as f:
            raw = f.read()
        lines = raw.strip().split("\n")
        title = lines[0].lstrip("# ").strip()
        body = "\n".join(lines[1:]).strip()
        all_docs.append({"id": name[:-3], "title": title, "chars": len(body)})

    with open(os.path.join(HERE, "corpus_index.json"), "w", encoding="utf-8") as f:
        json.dump(all_docs, f, ensure_ascii=False, indent=2)

    print(f"新增 {len(written)} 篇，跳过已存在 {len(skipped)} 篇")
    print(f"语料总数：{len(all_docs)} 篇")
    total = sum(d["chars"] for d in all_docs)
    print(f"总字数：  {total}")
    print()
    for d in written:
        print(f"  + {d['id']:18} {d['title']:20} {d['chars']:4} 字")


if __name__ == "__main__":
    main()
