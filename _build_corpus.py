# ============================================================
# 写出语料
# ============================================================
written = []
for doc_id, title, body in DOCS:
    path = os.path.join(DOCS_DIR, f"{doc_id}.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# {title}\n\n{body.strip()}\n")
    written.append({"id": doc_id, "title": title, "chars": len(body.strip())})

# 索引文件（方便程序读取，也方便人看）
index_path = os.path.join(HERE, "corpus_index.json")
with open(index_path, "w", encoding="utf-8") as f:
    json.dump(written, f, ensure_ascii=False, indent=2)

print(f"已生成 {len(written)} 个文档到 {DOCS_DIR}")
print()
total = 0
for d in written:
    print(f"  {d['id']:16} {d['title']:16} {d['chars']:5} 字")
    total += d["chars"]
print(f"\n  合计 {total} 字")
print(f"  索引：{index_path}")
